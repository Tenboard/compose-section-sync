package io.github.tenboard.composesectionsync

import androidx.compose.foundation.gestures.scrollBy
import androidx.compose.foundation.layout.Box
import androidx.compose.foundation.layout.height
import androidx.compose.foundation.layout.width
import androidx.compose.foundation.lazy.grid.GridCells
import androidx.compose.foundation.lazy.grid.GridItemSpan
import androidx.compose.foundation.lazy.grid.LazyGridState
import androidx.compose.foundation.lazy.grid.LazyVerticalGrid
import androidx.compose.foundation.lazy.grid.rememberLazyGridState
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.rememberCoroutineScope
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.unit.dp
import io.github.tenboard.section_sync.BoundarySelection
import io.github.tenboard.section_sync.NonSelectableItemSelection
import io.github.tenboard.section_sync.OngoingScrollBehavior
import io.github.tenboard.section_sync.SectionAnchor
import io.github.tenboard.section_sync.SectionPath
import io.github.tenboard.section_sync.SectionSyncOptions
import io.github.tenboard.section_sync.SectionSyncState
import io.github.tenboard.section_sync.rememberSectionSyncState
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.CoroutineStart
import kotlinx.coroutines.Job
import kotlinx.coroutines.job
import kotlinx.coroutines.launch
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test

class SectionSyncGapTest {
    @get:Rule
    val compose = createComposeRule()

    private val a = SectionPath.of("parent", "A")
    private val b = SectionPath.of("parent", "B")
    private val c = SectionPath.of("other", "C")
    private var anchors by mutableStateOf(listOf(
        SectionAnchor(a, 0), SectionAnchor(b, 20), SectionAnchor(c, 49),
    ))
    private var excluded by mutableStateOf(setOf(18, 19, 46, 47, 48))
    private var gapCount by mutableStateOf(0)
    private var options by mutableStateOf(SectionSyncOptions())
    private var shown by mutableStateOf(true)
    private lateinit var grid: LazyGridState
    private lateinit var sync: SectionSyncState<String>
    private lateinit var scope: CoroutineScope

    @Test
    fun keepCurrentWorksFromBothDirectionsAndDoesNotInventInitialSelection() {
        showGrid(initialIndex = 18)
        compose.runOnIdle { assertNull(sync.activePath) }
        jumpTo(0)
        assertSelected(a)
        jumpTo(18)
        assertSelected(a)
        jumpTo(20)
        assertSelected(b)
        jumpTo(19)
        assertSelected(b)
    }

    @Test
    fun automaticAndManualGapsKeepSelectionFromBothDirections() {
        gapCount = 1
        excluded = setOf(18, 46, 47)
        showGrid(initialIndex = 19)
        assertSelected(null)
        jumpTo(0)
        jumpTo(18)
        assertSelected(a)
        jumpTo(19)
        assertSelected(a)
        jumpTo(20)
        jumpTo(19)
        assertSelected(b)
        jumpTo(18)
        assertSelected(b)
    }

    @Test
    fun gapCountChangesCancelRequestsEvenWhenTheExcludedUnionIsUnchanged() {
        showGrid()
        jumpTo(19)
        val request = startPausedRequest(b)
        assertSelected(b)
        // The existing manual set already contains every index generated by count = 1.
        updateInputs { gapCount = 1 }
        compose.waitUntil { request.isCompleted }
        assertTrue(request.isCancelled)
        assertSelected(a)
        compose.runOnIdle { assertTrue(scope.coroutineContext.job.isActive) }
    }

    @Test
    fun gapCountChangesClearSuccessfulRetentionEvenWhenTheExcludedUnionIsUnchanged() {
        options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.PreviousSection)
        showGrid()
        runScroll { sync.scrollToSection(c) }
        assertSelected(c)
        updateInputs { gapCount = 1 }
        assertSelected(b)
    }

    @Test
    fun cancellationInAGapRestoresConfirmedSelectionAndPreservesTheCallerScope() {
        showGrid()
        jumpTo(18)
        val request = startPausedRequest(b)
        assertSelected(b)
        cancel(request)
        assertSelected(a)
        compose.runOnIdle { assertTrue(scope.coroutineContext.job.isActive) }

        // A successful later request is the new fallback, rather than the initial selection.
        runScroll { sync.scrollToSection(b) }
        jumpTo(19)
        val later = startPausedRequest(c)
        cancel(later)
        assertSelected(b)
    }

    @Test
    fun replacingAndThenCancellingRequestsDoesNotRestoreAnUnfinishedTarget() {
        showGrid()
        jumpTo(18)
        val first = startPausedRequest(b)
        val replacement = launchScroll { sync.animateScrollToSection(c) }
        compose.mainClock.advanceTimeUntil { sync.activePath == c }
        compose.waitUntil { first.isCompleted }
        compose.runOnIdle { assertTrue(grid.firstVisibleItemIndex in setOf(18, 19)) }
        assertTrue(first.isCancelled)
        cancel(replacement)
        assertSelected(a)
    }

    @Test
    fun discardedReplacementRestoresConfirmedSelection() {
        options = options.copy(ongoingScrollBehavior = OngoingScrollBehavior.InterruptAndDiscardRequest)
        showGrid()
        jumpTo(18)
        val first = startPausedRequest(b)
        val discarded = launchScroll { sync.animateScrollToSection(c) }
        compose.waitUntil { first.isCompleted && discarded.isCompleted }
        compose.mainClock.autoAdvance = true
        compose.waitForIdle()
        assertTrue(first.isCancelled)
        assertFalse(discarded.isCancelled)
        assertSelected(a)
        compose.runOnIdle { assertTrue(scope.coroutineContext.job.isActive) }
    }

    @Test
    fun successfulRequestRetentionPrecedesGapPolicyUntilTheOffsetChanges() {
        options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.PreviousSection)
        showGrid()
        runScroll { sync.scrollToSection(c) }
        assertSelected(c)
        val index = compose.runOnIdle {
            assertTrue(grid.firstVisibleItemIndex in excluded)
            assertTrue(grid.firstVisibleItemScrollOffset > 0)
            grid.firstVisibleItemIndex
        }
        runScroll { grid.scrollBy(-1f) }
        compose.runOnIdle { assertEquals(index, grid.firstVisibleItemIndex) }
        assertSelected(b)
    }

    @Test
    fun policyChangesDuringARequestReevaluateEvenWhenThePolicyIsChangedBack() {
        options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.PreviousSection)
        showGrid()
        val request = startPausedRequest(c)
        updateInputs { options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.NextSection) }
        updateInputs { options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.PreviousSection) }
        compose.runOnIdle { assertTrue(request.isActive) }
        compose.mainClock.autoAdvance = true
        compose.waitForIdle()
        assertTrue(request.isCompleted)
        assertFalse(request.isCancelled)
        assertSelected(b)
    }

    @Test
    fun ongoingScrollOptionChangesDoNotClearSuccessfulRequestRetention() {
        options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.PreviousSection)
        showGrid()
        val request = startPausedRequest(c)
        updateInputs { options = options.copy(ongoingScrollBehavior = OngoingScrollBehavior.InterruptAndDiscardRequest) }
        compose.mainClock.autoAdvance = true
        compose.waitForIdle()
        assertTrue(request.isCompleted)
        assertFalse(request.isCancelled)
        assertSelected(c)
    }

    @Test
    fun stationaryPolicyChangesClearRetainedSelection() {
        options = options.copy(nonSelectableItemSelection = NonSelectableItemSelection.PreviousSection)
        showGrid()
        runScroll { sync.scrollToSection(c) }
        assertSelected(c)
        updateInputs { options = options.copy(shortContentSelection = BoundarySelection.LastAnchor) }
        assertSelected(b)
    }

    @Test
    fun excludedMappingChangesCancelRequestsAndUseTheNewMapping() {
        showGrid()
        jumpTo(18)
        val request = startPausedRequest(b)
        updateInputs { excluded = excluded - 18 }
        compose.waitUntil { request.isCompleted }
        assertTrue(request.isCancelled)
        assertSelected(a)
        compose.runOnIdle { assertTrue(scope.coroutineContext.job.isActive) }
    }

    @Test
    fun removedConfirmedPathCannotBeRestoredWhenARequestIsCancelled() {
        showGrid()
        jumpTo(18)
        val request = startPausedRequest(b)
        updateInputs { anchors = anchors.filterNot { it.path == a } }
        compose.waitUntil { request.isCompleted }
        assertTrue(request.isCancelled)
        assertSelected(null)
    }

    @Test
    fun emptyAnchorsAndDisposalClearSelectionAndCancelPendingRequests() {
        showGrid()
        val request = startPausedRequest(b)
        updateInputs { anchors = emptyList() }
        compose.waitUntil { request.isCompleted }
        assertTrue(request.isCancelled)
        assertSelected(null)

        updateInputs { anchors = listOf(SectionAnchor(a, 0), SectionAnchor(b, 20)) }
        val next = startPausedRequest(b)
        updateInputs { shown = false }
        compose.waitUntil { next.isCompleted }
        assertTrue(next.isCancelled)
        assertSelected(null)
    }

    private fun showGrid(initialIndex: Int = 0) {
        compose.setContent {
            if (shown) {
                grid = rememberLazyGridState(initialFirstVisibleItemIndex = initialIndex)
                scope = rememberCoroutineScope()
                sync = rememberSectionSyncState(anchors, grid, options, excluded, gapCount)
                LazyVerticalGrid(
                    columns = GridCells.Fixed(2),
                    state = grid,
                    modifier = Modifier.width(200.dp).height(150.dp),
                ) {
                    items(50, span = { GridItemSpan(maxLineSpan) }) {
                        Box(Modifier.height(40.dp))
                    }
                }
            }
        }
        compose.waitForIdle()
    }

    private fun assertSelected(path: SectionPath<String>?) {
        compose.runOnIdle { assertEquals(path, sync.activePath) }
    }

    private fun jumpTo(index: Int) {
        runScroll { grid.scrollToItem(index) }
        compose.runOnIdle { assertEquals(index, grid.firstVisibleItemIndex) }
    }

    private fun launchScroll(block: suspend () -> Unit): Job = compose.runOnIdle {
        scope.launch(start = CoroutineStart.UNDISPATCHED) { block() }
    }

    private fun runScroll(block: suspend () -> Unit) {
        val job = launchScroll(block)
        compose.waitForIdle()
        assertTrue(job.isCompleted)
        assertFalse(job.isCancelled)
    }

    private fun startPausedRequest(path: SectionPath<String>): Job {
        compose.mainClock.autoAdvance = false
        return launchScroll { sync.animateScrollToSection(path) }.also {
            assertTrue(it.isActive)
        }
    }

    private fun cancel(job: Job) {
        compose.runOnIdle { job.cancel() }
        compose.waitUntil { job.isCompleted }
        compose.mainClock.autoAdvance = true
        compose.waitForIdle()
        assertTrue(job.isCancelled)
    }

    private fun updateInputs(block: () -> Unit) {
        compose.runOnIdle(block)
        compose.mainClock.advanceTimeByFrame()
        compose.waitForIdle()
    }
}
